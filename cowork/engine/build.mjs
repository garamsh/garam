// Bundles src/engine.js into the one script the Go adapter embeds:
// ES2015, because goja implements ES5.1 and most of ES2015 and not
// later syntax; an IIFE, because goja loads a script and not a module.
import { build } from "esbuild";

await build({
  entryPoints: ["src/engine.js"],
  bundle: true,
  format: "iife",
  target: "es2015",
  legalComments: "none",
  outfile: "../internal/collab/goja/engine.gen.js",
  banner: { js: "// Code generated by cowork/engine/build.mjs. DO NOT EDIT." },
});
