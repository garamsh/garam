// Package ca owns the certificate authority an organization signs its
// machine identities with (ADR-0014).
//
// Each organization has its own CA, created on the first certificate it
// needs, so a certificate issued by one organization does not chain
// against another's: tenancy holds in the trust root rather than in a
// check a caller could forget. An issued certificate carries the
// subject's GRN in a SAN URI and nothing else — no roles, no claims.
//
// The CA private key never reaches a column in the clear. It is sealed
// through [Sealer] with a key-encryption key the process is given at
// boot, so a database dump alone signs nothing.
//
// A subject's own key reaches a certificate one of two ways. [Service]
// generates it, returns it once and stores it nowhere; or the subject
// generates it where the certificate will be used and sends a
// certificate signing request, and garam signs a key it never holds
// (ADR-0064). The second is what an enrolling operator does.
package ca

import (
	"time"

	"github.com/garamsh/garam/internal/errorx"
	"github.com/garamsh/garam/internal/grn"
)

// Domain sentinel errors.
var (
	ErrAuthorityNotFound      = errorx.New(errorx.KindNotFound, "certificate authority not found")
	ErrAuthorityAlreadyExists = errorx.New(errorx.KindAlreadyExists, "certificate authority already exists")
)

// Authority is an organization's certificate authority: the certificate
// it signs with, and the private key behind it in sealed form. Every
// field is one the store writes and reads back, and the aggregate
// holds no invariant over any of them, so they are exported and
// whatever restores a row does it from outside this package
// (ADR-0069).
//
// SealedKey is the private key as [Sealer] sealed it, so reading it
// yields no key material. NotAfter is the same instant the certificate
// itself carries, stored beside it. CreatedAt is the first time the
// organization needed a CA.
type Authority struct {
	Organization grn.GRN
	Certificate  []byte
	SealedKey    []byte
	NotAfter     time.Time
	CreatedAt    time.Time
}

// Certificate is a signed client certificate and the CA that signed
// it. It holds no private key, and the value has nowhere to put one:
// what garam signed over may have been generated by the caller, in
// which case garam never saw the key and never can (ADR-0064).
type Certificate struct {
	subject   grn.GRN
	serial    string
	certPEM   []byte
	issuerPEM []byte
	notAfter  time.Time
}

// IssuedCertificate is a Certificate garam generated the key pair for.
// The private key exists in this value alone — it is generated per
// certificate and never stored, so a caller that loses it reissues
// rather than recovers.
//
// It is a type of its own rather than a nullable field, so that the
// path which signs a caller's own key has no key field to leave empty
// and no accessor to answer with nothing.
type IssuedCertificate struct {
	Certificate
	keyPEM []byte
}

// PrivateKeyPEM returns the private key in PKCS#8 PEM form.
func (c *IssuedCertificate) PrivateKeyPEM() []byte { return c.keyPEM }

// Subject returns the GRN the certificate identifies, which is also
// what its SAN URI holds.
func (c *Certificate) Subject() grn.GRN { return c.subject }

// Serial returns the certificate's serial number in decimal. Two
// certificates naming one subject are told apart by it, which is what a
// renewal of one of them has to name (ADR-0046).
func (c *Certificate) Serial() string { return c.serial }

// CertificatePEM returns the certificate in PEM form.
func (c *Certificate) CertificatePEM() []byte { return c.certPEM }

// IssuerPEM returns the signing CA certificate in PEM form: the
// authority this certificate chains to. It is not what garam is
// verified against — the two directions rest on different roots, and
// the one a holder pins garam by travels beside this (ADR-0040).
func (c *Certificate) IssuerPEM() []byte { return c.issuerPEM }

// NotAfter returns when the certificate stops being valid. It carries
// jitter, so certificates issued together do not expire together.
func (c *Certificate) NotAfter() time.Time { return c.notAfter }
