// Store implements message.Store against PostgreSQL. The queries are
// generated by sqlc from queries.sql; it holds no message and no
// recipient of its own, so two of these serve one queue.
type Store struct {
	pool *pgxpool.Pool
	q    *db.Queries
}

// Compile-time check that Store satisfies message.Store.
var _ message.Store = (*Store)(nil)

// New constructs a Postgres-backed message store.
func New(pool *pgxpool.Pool) *Store {
	return &Store{pool: pool, q: db.New(pool)}
}

// fenced runs fn in one local transaction that the agent execution
// fence admits first (ADR-0080): the fence holds the agent's execution
// row until fn's writes commit, so a replacement of that execution
// either waits for them or is what refuses them. A nil fence is a
// write of an identity that is not an agent, which no execution
// fences, so it runs on the pool.
func (s *Store) fenced(ctx context.Context, op string, fence *message.Fence, fn func(q *db.Queries) error) error {
	if fence == nil {
		return fn(s.q)
	}
	return s.transaction(ctx, op, fence, func(q *db.Queries, _ pgx.Tx) error { return fn(q) })
}

// transaction runs fn in one local transaction, admitted first by the
// fence where there is one, for writes that commit together or not at
// all.
func (s *Store) transaction(ctx context.Context, op string, fence *message.Fence, fn func(q *db.Queries, tx pgx.Tx) error) error {
	tx, err := s.pool.Begin(ctx)
	if err != nil {
		return errorx.Wrap(err, op+": begin", errorx.KindUnavailable)
	}
	defer func() { _ = tx.Rollback(ctx) }()
	q := s.q.WithTx(tx)
	if fence != nil {
		answer, err := q.AdmitExecution(ctx, db.AdmitExecutionParams{
			AgentGrn:  fence.Agent.String(),
			TokenHash: fence.TokenHash,
			Serial:    fence.Serial,
			NotBefore: pgxtype.Timestamptz(fence.NotBefore),
			NotAfter:  pgxtype.Timestamptz(fence.NotAfter),
		})
		if err != nil {
			return errorx.Wrap(pgxerr.Classify(err, op+": admit", nil, nil), op, errorx.KindUnavailable)
		}
		if err := refusalOf(answer); err != nil {
			return err
		}
	}
	if err := fn(q, tx); err != nil {
		return err
	}
	if err := tx.Commit(ctx); err != nil {
		return errorx.Wrap(err, op+": commit", errorx.KindUnavailable)
	}
	return nil
}

// refusalOf reads the answer of agent_execution_admit, the agent
// execution fence's declared surface (ADR-0080): nil for an admitted
// write, and the refusal it names otherwise.
func refusalOf(answer string) error {
	switch answer {
	case "admitted":
		return nil
	case "unknown_agent":
		return errorx.New(errorx.KindNotFound, "agent not found")
	case "token_required":
		return errorx.New(errorx.KindUnauthenticated, "execution token required")
	case "token_stale":
		return errorx.New(errorx.KindPermissionDenied, "execution token is not current")
	case "credential_fenced":
		return errorx.New(errorx.KindFailedPrecondition, "credential is not current")
	}
	return errorx.New(errorx.KindInternal, "unknown admission answer")
}

// Enqueue stores the message, or returns the one the sender already
// stored under the same key. Storing is the queue's one write, so the
// retention sweep rides it: an undelivered message older than the
// window is deleted first, which keeps the table proportional to what
// is live (ADR-0034). The sweep runs ahead of the insert rather than in
// it, because a data-modifying CTE shares the insert's snapshot — the
// conflicting row it deletes would still conflict. The send's audit
// event commits with the insert, fenced or not (ADR-0106).
func (s *Store) Enqueue(ctx context.Context, m *message.Message, fence *message.Fence) (*message.Message, error) {
	var stored *message.Message
	err := s.transaction(ctx, "enqueue", fence, func(q *db.Queries, tx pgx.Tx) error {
		if err := q.DeleteExpiredMessages(ctx, interval(message.RetentionWindow)); err != nil {
			return pgxerr.Classify(err, "sweep", nil, nil)
		}
		row, err := q.EnqueueMessage(ctx, db.EnqueueMessageParams{
			ID:             string(m.ID),
			RecipientGrn:   m.Recipient.String(),
			SenderGrn:      m.Sender.String(),
			IdempotencyKey: m.IdempotencyKey,
			Body:           pgtype.Text{String: m.Body, Valid: true},
			Author:         string(m.Author),
		})
		if err != nil {
			return pgxerr.Classify(err, "enqueue", nil, nil)
		}
		if stored, err = rowToMessage(row); err != nil {
			return err
		}
		return auditpg.RecordSend(ctx, tx, message.Sent(m, stored))
	})
	if err != nil {
		return nil, err
	}
	return stored, nil
}

// EnqueueWithinBudget answers what the sender's key stores, and tries
// the insert the budget gates only where it stores nothing, so a
// stored result is answered after the budget too (ADR-0083). The
// sweep rides it as it rides Enqueue. The key is read again after an
// admitted insert, because the row admitted may be one a concurrent
// submission stored first. The send's audit event commits with what
// the key stores; a refusal records none and still commits the sweep
// (ADR-0106).
func (s *Store) EnqueueWithinBudget(ctx context.Context, m *message.Message, created time.Time, fence *message.Fence) (*message.Message, error) {
	key := db.MessageByKeyParams{SenderGrn: m.Sender.String(), IdempotencyKey: m.IdempotencyKey}
	var stored *message.Message
	var refused error
	err := s.transaction(ctx, "enqueue within budget", fence, func(q *db.Queries, tx pgx.Tx) error {
		if err := q.DeleteExpiredMessages(ctx, interval(message.RetentionWindow)); err != nil {
			return pgxerr.Classify(err, "sweep", nil, nil)
		}
		row, err := q.MessageByKey(ctx, key)
		switch {
		case errors.Is(err, pgx.ErrNoRows):
			row, err = insertWithinBudget(ctx, q, key, m, created)
		case err != nil:
			err = pgxerr.Classify(err, "stored under key", nil, nil)
		}
		if isRefusal(err) {
			refused = err
			return nil
		}
		if err != nil {
			return err
		}
		if !sameSubmission(row, m) {
			refused = message.ErrKeyHoldsAnotherMessage
			return nil
		}
		if stored, err = rowToMessage(row); err != nil {
			return err
		}
		return auditpg.RecordSend(ctx, tx, message.Sent(m, stored))
	})
	if err != nil {
		return nil, err
	}
	if refused != nil {
		return nil, refused
	}
	return stored, nil
}

// isRefusal reports whether err is the budget's answer to a submission
// rather than a failure to give one.
func isRefusal(err error) bool {
	return errors.Is(err, message.ErrCreatedLater) || errors.Is(err, message.ErrSubmissionExpired)
}

// insertWithinBudget tries the insert the budget gates for a key that
// stores nothing, and reads back what the key stores once it is
// admitted.
func insertWithinBudget(ctx context.Context, q *db.Queries, key db.MessageByKeyParams, m *message.Message, created time.Time) (db.Message, error) {
	verdict, err := q.EnqueueWithinBudget(ctx, db.EnqueueWithinBudgetParams{
		Created:        pgxtype.Timestamptz(created),
		ID:             string(m.ID),
		RecipientGrn:   m.Recipient.String(),
		SenderGrn:      m.Sender.String(),
		IdempotencyKey: m.IdempotencyKey,
		Body:           m.Body,
		Author:         string(m.Author),
		Budget:         interval(message.SubmissionBudget),
	})
	if err != nil {
		return db.Message{}, pgxerr.Classify(err, "enqueue within budget", nil, nil)
	}
	if err := budgetRefusal(verdict); err != nil {
		return db.Message{}, err
	}
	row, err := q.MessageByKey(ctx, key)
	return row, pgxerr.Classify(err, "stored under key", nil, nil)
}

// Refuse writes the refused send's audit event alone, fenced as the
// post it answers would have been (ADR-0106).
func (s *Store) Refuse(ctx context.Context, sender, recipient grn.GRN, fence *message.Fence) error {
	return s.transaction(ctx, "refuse", fence, func(_ *db.Queries, tx pgx.Tx) error {
		return auditpg.RecordSend(ctx, tx, audit.Refused(sender, recipient))
	})
}

// budgetRefusal reads the verdict EnqueueWithinBudget decided: nil for
// a stored row, and the refusal it names otherwise.
func budgetRefusal(verdict string) error {
	switch verdict {
	case "admitted":
		return nil
	case "later":
		return message.ErrCreatedLater
	case "expired":
		return message.ErrSubmissionExpired
	}
	return errorx.New(errorx.KindInternal, "unknown budget verdict")
}

// sameSubmission reports whether the row stored under m's key is m's
// own submission. A completed row has dropped its body (ADR-0034), so
// the key and recipient are what bind a retry to it then.
func sameSubmission(row db.Message, m *message.Message) bool {
	return row.RecipientGrn == m.Recipient.String() && (!row.Body.Valid || row.Body.String == m.Body)
}

// Claim hands the recipient's oldest ready message to one reader and
// holds it for lease, or returns ErrNoMessageReady. A message that has
// been handed out maxAttempts times is not ready for anyone. The claim
// and handOut share one transaction, fenced or not, so a hand-out that
// fails rolls the claim back.
func (s *Store) Claim(ctx context.Context, recipient grn.GRN, lease time.Duration, maxAttempts int, fence *message.Fence, handOut func(*message.Claim) error) (*message.Claim, error) {
	claimID, err := message.NewClaimID()
	if err != nil {
		return nil, err
	}
	var claim *message.Claim
	claimed := func(q *db.Queries) error {
		// The lease travels as an interval, so Postgres's clock decides
		// when the claim lapses and this process's never does.
		row, err := q.ClaimMessage(ctx, db.ClaimMessageParams{
			ClaimID:      pgtype.Text{String: string(claimID), Valid: true},
			Lease:        interval(lease),
			RecipientGrn: recipient.String(),
			MaxAttempts:  attemptBound(maxAttempts),
		})
		if err != nil {
			return pgxerr.Classify(err, "claim", message.ErrNoMessageReady, nil)
		}
		if claim, err = rowToClaim(row); err != nil || handOut == nil {
			return err
		}
		return handOut(claim)
	}
	err = s.transaction(ctx, "claim", fence, func(q *db.Queries, _ pgx.Tx) error { return claimed(q) })
	if err != nil {
		return nil, err
	}
	return claim, nil
}

// Renew extends a live claim's lease under the ceiling. A claim that
// lapsed, was handed on, or was completed matches no row, hence
// ErrStaleClaim.
func (s *Store) Renew(ctx context.Context, recipient grn.GRN, id message.ClaimID, lease, ceiling time.Duration, fence *message.Fence) (*message.Claim, error) {
	var row db.Message
	err := s.fenced(ctx, "renew", fence, func(q *db.Queries) error {
		var err error
		row, err = q.RenewClaim(ctx, db.RenewClaimParams{
			Lease:        interval(lease),
			Ceiling:      interval(ceiling),
			RecipientGrn: recipient.String(),
			ClaimID:      pgtype.Text{String: string(id), Valid: true},
		})
		return pgxerr.Classify(err, "renew", message.ErrStaleClaim, nil)
	})
	if err != nil {
		return nil, err
	}
	return rowToClaim(row)
}

// Complete reports the claimed message delivered. A claim handed on to
// another reader matches no row, hence ErrStaleClaim.
func (s *Store) Complete(ctx context.Context, recipient grn.GRN, id message.ClaimID, fence *message.Fence) error {
	return s.fenced(ctx, "complete", fence, func(q *db.Queries) error {
		rows, err := q.CompleteMessage(ctx, db.CompleteMessageParams{
			RecipientGrn: recipient.String(),
			ClaimID:      pgtype.Text{String: string(id), Valid: true},
		})
		if err != nil {
			return pgxerr.Classify(err, "complete", nil, nil)
		}
		if rows == 0 {
			return message.ErrStaleClaim
		}
		return nil
	})
}

// Status returns how far the sender's message has got. A sender that
// stored none under the identifier matches no row, hence
// ErrNoSuchMessage — which is also what a message the sweep deleted
// answers, because absence is what expiry looks like (ADR-0055).
func (s *Store) Status(ctx context.Context, sender grn.GRN, id message.ID, maxAttempts int, fence *message.Fence) (*message.Status, error) {
	var row db.MessageStatusRow
	err := s.fenced(ctx, "message status", fence, func(q *db.Queries) error {
		var err error
		row, err = q.MessageStatus(ctx, db.MessageStatusParams{
			MaxAttempts: attemptBound(maxAttempts),
			ID:          string(id),
			SenderGrn:   sender.String(),
		})
		return pgxerr.Classify(err, "message status", message.ErrNoSuchMessage, nil)
	})
	if err != nil {
		return nil, err
	}
	state, err := parseState(row.State)
	if err != nil {
		return nil, err
	}
	return &message.Status{ID: message.ID(row.ID), State: state, Attempts: int(row.Attempts), CreatedAt: row.CreatedAt.Time}, nil
}

// parseState reads the state the query decided. The set is closed and
// the query is the only writer of it, so a value outside it is this
// process reading a statement it no longer matches.
func parseState(s string) (message.State, error) {
	switch message.State(s) {
	case message.StatePending, message.StateClaimed, message.StateCompleted, message.StateExhausted:
		return message.State(s), nil
	default:
		return "", errorx.New(errorx.KindInternal, "message: unknown state "+s)
	}
}

// rowToMessage converts a sqlc row into the domain aggregate. A stored
// value that no longer parses is data corruption, hence internal.
func rowToMessage(row db.Message) (*message.Message, error) {
	recipient, err := grn.Parse(row.RecipientGrn)
	if err != nil {
		return nil, errorx.Wrap(err, "recipient grn", errorx.KindInternal)
	}
	sender, err := grn.Parse(row.SenderGrn)
	if err != nil {
		return nil, errorx.Wrap(err, "sender grn", errorx.KindInternal)
	}
	author, err := message.ParseAuthor(row.Author)
	if err != nil {
		return nil, errorx.Wrap(err, "author", errorx.KindInternal)
	}
	return &message.Message{
		ID:             message.ID(row.ID),
		Recipient:      recipient,
		Sender:         sender,
		IdempotencyKey: row.IdempotencyKey,
		// A completed row's body is dropped, and the schema refuses the
		// half-states, so an absent body reads as none rather than as
		// corruption.
		Body:      row.Body.String,
		Author:    author,
		CreatedAt: row.CreatedAt.Time,
		Attempts:  int(row.Attempts),
	}, nil
}

// rowToClaim converts the row a claim just wrote. The claim columns are
// what that write set, so a row without them is data corruption.
func rowToClaim(row db.Message) (*message.Claim, error) {
	m, err := rowToMessage(row)
	if err != nil {
		return nil, err
	}
	if !row.ClaimID.Valid || !row.ClaimExpiresAt.Valid || !row.ClaimedAt.Valid {
		return nil, errorx.New(errorx.KindInternal, "claimed row carries no claim")
	}
	// A claim matches only an undelivered row, which the schema requires
	// to be carrying its body.
	if !row.Body.Valid {
		return nil, errorx.New(errorx.KindInternal, "claimed row carries no body")
	}
	return &message.Claim{
		Message:   m,
		ID:        message.ClaimID(row.ClaimID.String),
		ClaimedAt: row.ClaimedAt.Time,
		ExpiresAt: row.ClaimExpiresAt.Time,
	}, nil
}

// interval converts a duration to the interval Postgres measures a
// lease with.
func interval(d time.Duration) pgtype.Interval {
	return pgtype.Interval{Microseconds: d.Microseconds(), Valid: true}
}

// attemptBound narrows the bound to the column's width. A wider one
// means no bound at all, and narrowing it silently would wrap into a
// negative one, which withholds every message instead.
func attemptBound(maxAttempts int) int32 {
	if maxAttempts > math.MaxInt32 {
		return math.MaxInt32
	}
	return int32(maxAttempts)
}
